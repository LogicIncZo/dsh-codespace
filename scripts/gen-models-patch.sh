#!/usr/bin/env bash
# Generate a dsh --patch overlay that wires two provider routes:
#   zen — OpenCode Zen gateway (https://opencode.ai/zen/v1, key: OPENCODE_ZEN_API_KEY)
#   zai — Z.AI GLM Coding Plan (built-in pi-ai catalog, key: ZAI_API_KEY)
#
# Usage: gen-models-patch.sh [output-path]   (default: "$HOME/.dsh/cc-models.yml")
# Env overrides:
#   DSH_DEFAULT_PROVIDER  zai (default) | zen
#   DSH_DEFAULT_MODEL     glm-5.3-flash (default)
#   ZEN_BASE_URL          https://opencode.ai/zen/v1
#
# The zen model list is fetched live from the Zen /models endpoint when
# OPENCODE_ZEN_API_KEY is set; otherwise a baked-in snapshot is used.
# Rerun this script any time to refresh the list.
set -euo pipefail

OUT="${1:-$HOME/.dsh/cc-models.yml}"
ZEN_BASE_URL="${ZEN_BASE_URL:-https://opencode.ai/zen/v1}"
DSH_DEFAULT_PROVIDER="${DSH_DEFAULT_PROVIDER:-zai}"
DSH_DEFAULT_MODEL="${DSH_DEFAULT_MODEL:-glm-5.3-flash}"

# Baked snapshot 2026-10-02 (35 models minus the 'test' ping model).
FALLBACK_MODELS="big-pickle
claude-fable-5-1
claude-opus-5-5
claude-sonnet-5-5
deepseek-v4.1-flash
fledge-alpha-free
gemini-3.5-flash-lite
gemini-3.6-flash
gemini-3.7-flash
gemini-3.8-flash
glm-5.3
glm-5.3-flash
gpt-5.6-luna
gpt-5.6-sol
gpt-5.6-terra
gpt-6-astra
gpt-6-luna
gpt-6-sol
gpt-6.1-sol
grok-4.6
grok-4.7
jev-1.13
jev-1.13-free
longcat-2.5-preview-free
mimo-v2.5-free
mimo-v2.6-flash-free
muse-spark-1.2
muse-spark-1.2-contributor-free
muse-spark-1.3
muse-spark-1.3-contributor-free
nemotron-3.5-lightning-free
qwen3.8-flash
qwen3.8-max
space-bunny-free"

MODELS="$FALLBACK_MODELS"
SOURCE="baked snapshot 2026-10-02"
if [[ -n "${OPENCODE_ZEN_API_KEY:-}" ]]; then
  LIVE="$(curl -fsSL -m 20 "${ZEN_BASE_URL}/models" \
    -H "Authorization: Bearer ${OPENCODE_ZEN_API_KEY}" 2>/dev/null |
    node -e 'let s="";process.stdin.on("data",d=>s+=d);process.stdin.on("end",()=>{try{const j=JSON.parse(s);console.log((j.data||[]).map(m=>String(m.id||"").trim()).filter(i=>i&&i!=="test").sort().join("\n"))}catch(e){}})' || true)"
  if [[ -n "$LIVE" ]]; then
    MODELS="$LIVE"
    SOURCE="live from ${ZEN_BASE_URL}/models"
  fi
fi

if [[ "$DSH_DEFAULT_PROVIDER" != "zen" && "$DSH_DEFAULT_PROVIDER" != "zai" ]]; then
  echo "gen-models-patch.sh: DSH_DEFAULT_PROVIDER must be 'zen' or 'zai' (got: $DSH_DEFAULT_PROVIDER)" >&2
  exit 1
fi

mkdir -p "$(dirname "$OUT")"
{
  echo "# cc-models.yml — dsh provider patch: OpenCode Zen + Z.AI subscription"
  echo "# Generated by scripts/gen-models-patch.sh (zen list: ${SOURCE})."
  echo "# Do not hand-edit; rerun the generator instead."
  echo "# Apply with: dsh tui --patch ~/.dsh/cc-models.yml"
  echo "#   or headless: DSH_PERMISSION_MODE=danger-full-access dsh --profile headless --patch ~/.dsh/cc-models.yml \"task\""
  echo "- id: llm-pi-ai"
  echo "  config:"
  echo "    providers:"
  echo "      zen:"
  echo "        displayName: OpenCode Zen"
  echo "        apiKeyEnv: OPENCODE_ZEN_API_KEY"
  echo "        api: openai-completions"
  echo "        baseURL: ${ZEN_BASE_URL}"
  echo "        defaultContextWindow: 262144"
  echo "        models:"
  while IFS= read -r m; do
    [[ -z "$m" ]] && continue
    # Free-tier zen models reject non-OpenCode clients (403 FreeTierError);
    # keep them listed for completeness but mark them.
    if [[ "$m" == *free* || "$m" == "big-pickle" ]]; then
      echo "          - id: ${m}   # free tier - OpenCode clients only (403 from dsh)"
    else
      echo "          - id: ${m}"
    fi
    echo "            name: ${m}"
  done <<< "$MODELS"
  echo "      zai:"
  echo "        displayName: Z.AI (GLM Coding Plan)"
  echo "        apiKeyEnv: ZAI_API_KEY"
  echo "- id: agent-default-model"
  echo "  config:"
  echo "    provider: ${DSH_DEFAULT_PROVIDER}"
  echo "    model: ${DSH_DEFAULT_MODEL}"
} > "$OUT"

echo "gen-models-patch.sh: wrote ${OUT} ($(echo "$MODELS" | grep -c .) zen models, default ${DSH_DEFAULT_PROVIDER}/${DSH_DEFAULT_MODEL})"
